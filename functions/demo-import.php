		<h1>Наполнение Kompas Indoor</h1>
		<p>Скрипт создаёт или обновляет страницы и три услуги, записывает тексты в ACF и обычный редактор WordPress. Изображения, галереи и логотипы не загружаются и не очищаются.</p>
